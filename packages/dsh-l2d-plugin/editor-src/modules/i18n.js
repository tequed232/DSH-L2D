  normalize: function (code) {
    var c = String(code || '').toLowerCase().replace('_', '-');
    if (!c) return null;
    if (c.indexOf('zh') === 0) return 'zh-CN';
    if (c.indexOf('ja') === 0) return 'ja';
    if (c.indexOf('en') === 0) return 'en';
    return null;
  },
  detect: function () {
    var pick = null;
    try { pick = this.normalize(new URLSearchParams(window.location.search).get('lang')); } catch (err) { pick = null; }
    if (!pick) { try { pick = this.normalize(localStorage.getItem(this.KEY)); } catch (err) { /* file:// 降级 */ } }
    if (!pick) {
      var list = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language];
      for (var i = 0; i < list.length && !pick; i++) pick = this.normalize(list[i]);
    }
    return pick || this.FALLBACK;
  },
  has: function (key) { return Object.prototype.hasOwnProperty.call(this.dict[this.lang] || {}, key); },
  t: function (key, params) {
    var d = this.dict[this.lang] || {}, s = d[key];
    if (typeof s !== 'string') {
      this.missing[this.lang + ':' + key] = true;
      s = this.dict[this.FALLBACK][key];
      if (typeof s !== 'string') s = key;
    }
    if (params) s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] === undefined ? m : String(params[k]); });
    return s;
  },
  reason: function (code) {
    var c = String(code == null ? '' : code);
    return c && this.has('reason.' + c) ? this.t('reason.' + c) : c;
  },
  outcome: function (code) {
    var c = String(code == null ? '' : code);
    return c && this.has('outcome.' + c) ? this.t('outcome.' + c) : c;
  },
  apply: function (root) {
    var self = this, r = root || document;
    var each = function (attr, fn) {
      Array.prototype.forEach.call(r.querySelectorAll('[' + attr + ']'), function (el) { fn(el, self.t(el.getAttribute(attr))); });
    };
    each('data-i18n', function (el, s) { el.textContent = s; });
    each('data-i18n-title', function (el, s) { el.title = s; });
    each('data-i18n-aria', function (el, s) { el.setAttribute('aria-label', s); });
    each('data-i18n-ph', function (el, s) { el.setAttribute('placeholder', s); });
  },
  set: function (code, opts) {
    var lang = this.normalize(code) || this.FALLBACK;
    var changed = lang !== this.lang;
    this.lang = lang;
    document.documentElement.setAttribute('lang', lang);
    if (!opts || opts.persist !== false) { try { localStorage.setItem(this.KEY, lang); } catch (err) { /* ignore */ } }
    this.apply(document);
    var sel = document.getElementById('lang-select');
    if (sel && sel.value !== lang) sel.value = lang;
    if (changed || (opts && opts.force)) this.listeners.forEach(function (fn) { try { fn(lang); } catch (err) { /* 单个订阅失败不影响其他 */ } });
    return lang;
  },
  onChange: function (fn) { this.listeners.push(fn); },
  audit: function () {
    var base = Object.keys(this.dict[this.FALLBACK]).sort(), self = this, out = { ok: true, size: base.length, diff: {} };
    this.LOCALES.forEach(function (l) {
      var ks = Object.keys(self.dict[l] || {});
      var miss = base.filter(function (k) { return ks.indexOf(k) < 0 || typeof self.dict[l][k] !== 'string' || !self.dict[l][k]; });
      var extra = ks.filter(function (k) { return base.indexOf(k) < 0; });
      if (miss.length || extra.length) { out.ok = false; out.diff[l] = { missing: miss, extra: extra }; }
    });
    return out;
  },
  init: function () {
    var sel = document.getElementById('lang-select'), self = this;
    if (sel) {
      sel.innerHTML = this.LOCALES.map(function (l) { return '<option value="' + l + '">' + self.NAMES[l] + '</option>'; }).join('');
      sel.addEventListener('change', function () { self.set(sel.value); });
    }
    this.set(this.detect(), { persist: false, force: true });
  }
